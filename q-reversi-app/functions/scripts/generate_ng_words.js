const fs = require("fs");
const path = require("path");

const root = __dirname;

function readLines(file) {
  return fs
    .readFileSync(path.join(root, file), "utf8")
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
}

function normalize(raw) {
  return raw
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s\u3000_\-・･./\\|'"`~!@#$%^&*()+=\[\]{};:,<>?？！。、「」『』（）]/g, "");
}

