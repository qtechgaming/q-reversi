const merged = new Map();

function add(raw, minLen) {
  const trimmed = raw.trim();
  if (!trimmed) return;
  const n = normalize(trimmed);
  if (!n || n.length < minLen) return;
  if (FALSE_POSITIVES.has(n)) return;
  const prev = merged.get(n);
  if (!prev || trimmed.length > prev.length) {
    merged.set(n, trimmed);
  }
}

